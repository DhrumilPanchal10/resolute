#!/usr/bin/env python3
"""Unified evaluation report and CI gate.

Runs the 40-case offline smoke subset (5 multi-agent issues, 10 scenarios,
5+5 adversarial tickets), checks results against thresholds.yaml, and
writes docs/results/summary.md.

Usage:
    OFFLINE=1 python evals/report.py           # run + report + gate check
    OFFLINE=1 python evals/report.py --no-gate  # run + report only
"""
from __future__ import annotations

import asyncio
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT))

THRESHOLDS_PATH = ROOT / "evals" / "thresholds.yaml"
DOCS_RESULTS = ROOT / "docs" / "results"


def load_thresholds() -> dict[str, Any]:
    with THRESHOLDS_PATH.open() as fh:
        return yaml.safe_load(fh)


# ---------------------------------------------------------------------------
# Runners (import lazily to avoid circular deps at module level)
# ---------------------------------------------------------------------------


async def run_multi_agent_smoke() -> dict[str, Any]:
    from evals.run import run_eval
    rows = await run_eval(limit=5)
    n = len(rows)
    if n == 0:
        return {"n": 0, "triage_rate": 0.0, "reply_rate": 0.0, "rows": []}
    triaged = sum(1 for r in rows if r.triage_category)
    replied = sum(1 for r in rows if r.answer)
    return {
        "n": n,
        "triage_rate": triaged / n,
        "reply_rate": replied / n,
        "avg_latency_ms": sum(r.latency_ms for r in rows) / n,
        "rows": rows,
    }


async def run_scenarios_smoke() -> dict[str, Any]:
    from evals.scenarios.runner import run_all
    scenarios_path = ROOT / "evals" / "scenarios" / "scenarios.yaml"
    results = await run_all(scenarios_path, k=1, limit=10)
    n = len(results)
    if n == 0:
        return {"n": 0, "pass_at_1": 0.0, "pass_at_k": 0.0}
    pass1 = sum(1 for r in results if r.pass_at_1)
    passk = sum(1 for r in results if r.pass_at_k)
    return {
        "n": n,
        "pass_at_1": pass1 / n,
        "pass_at_k": passk / n,
        "results": results,
    }


async def run_adversarial_smoke() -> dict[str, Any]:
    from evals.adversarial.suite import run_suite
    report = await run_suite(limit_injected=5, limit_benign=5)
    return {
        "total_injected": report.total_injected,
        "total_benign": report.total_benign,
        "injected_blocked": report.injected_blocked,
        "injected_leaked": report.injected_leaked,
        "asr": report.asr,
        "benign_answered": report.benign_answered,
        "benign_success_rate": report.benign_success_rate,
    }


# ---------------------------------------------------------------------------
# Report generation
# ---------------------------------------------------------------------------


def generate_summary(
    ma: dict[str, Any],
    sc: dict[str, Any],
    adv: dict[str, Any],
    thresholds: dict[str, Any],
    gate_results: list[tuple[str, bool, str]],
) -> str:
    date_str = datetime.now().strftime("%Y-%m-%d")
    gate_status = "PASS" if all(ok for _, ok, _ in gate_results) else "FAIL"

    md = f"""# Evaluation Summary

**Date:** {date_str}
**Mode:** offline (canned LLM responses)
**Gate:** {gate_status}

---

## Multi-Agent Evaluation

| Metric | Value | Threshold |
|--------|-------|-----------|
| Issues evaluated | {ma['n']} | — |
| Triage rate | {ma['triage_rate']:.0%} | ≥ {thresholds['multi_agent']['min_triage_rate']:.0%} |
| Reply rate | {ma['reply_rate']:.0%} | ≥ {thresholds['multi_agent']['min_reply_rate']:.0%} |
| Avg latency | {ma.get('avg_latency_ms', 0):.0f} ms | — |

## Scenario Evaluation

| Metric | Value | Threshold |
|--------|-------|-----------|
| Scenarios evaluated | {sc['n']} | — |
| pass@1 | {sc['pass_at_1']:.0%} | ≥ {thresholds['scenarios']['min_pass_at_1']:.0%} |
| pass@k | {sc['pass_at_k']:.0%} | ≥ {thresholds['scenarios']['min_pass_at_k']:.0%} |

## Adversarial Evaluation

| Metric | Value | Threshold |
|--------|-------|-----------|
| Injected tickets | {adv['total_injected']} | — |
| Blocked by guardrails | {adv['injected_blocked']} | — |
| Attack successes (leaked) | {adv['injected_leaked']} | — |
| **ASR** | **{adv['asr']:.1%}** | ≤ {thresholds['adversarial']['max_asr']:.0%} |
| Benign tickets | {adv['total_benign']} | — |
| Benign answered | {adv['benign_answered']} | — |
| **Benign success rate** | **{adv['benign_success_rate']:.0%}** | ≥ {thresholds['adversarial']['min_benign_success']:.0%} |

## CI Gate Results

| Check | Result | Detail |
|-------|--------|--------|
"""
    for name, ok, detail in gate_results:
        md += f"| {name} | {'PASS' if ok else 'FAIL'} | {detail} |\n"

    md += f"""
---

*Generated by `evals/report.py` · thresholds from `evals/thresholds.yaml`*
"""
    return md


# ---------------------------------------------------------------------------
# Gate checks
# ---------------------------------------------------------------------------


def check_gate(
    ma: dict[str, Any],
    sc: dict[str, Any],
    adv: dict[str, Any],
    thresholds: dict[str, Any],
) -> list[tuple[str, bool, str]]:
    results: list[tuple[str, bool, str]] = []
    t = thresholds

    # Multi-agent
    ok = ma["triage_rate"] >= t["multi_agent"]["min_triage_rate"]
    results.append(("multi_agent.triage_rate", ok, f"{ma['triage_rate']:.0%} ≥ {t['multi_agent']['min_triage_rate']:.0%}"))

    ok = ma["reply_rate"] >= t["multi_agent"]["min_reply_rate"]
    results.append(("multi_agent.reply_rate", ok, f"{ma['reply_rate']:.0%} ≥ {t['multi_agent']['min_reply_rate']:.0%}"))

    # Scenarios
    ok = sc["pass_at_1"] >= t["scenarios"]["min_pass_at_1"]
    results.append(("scenarios.pass_at_1", ok, f"{sc['pass_at_1']:.0%} ≥ {t['scenarios']['min_pass_at_1']:.0%}"))

    ok = sc["pass_at_k"] >= t["scenarios"]["min_pass_at_k"]
    results.append(("scenarios.pass_at_k", ok, f"{sc['pass_at_k']:.0%} ≥ {t['scenarios']['min_pass_at_k']:.0%}"))

    # Adversarial
    ok = adv["asr"] <= t["adversarial"]["max_asr"]
    results.append(("adversarial.asr", ok, f"{adv['asr']:.1%} ≤ {t['adversarial']['max_asr']:.0%}"))

    ok = adv["benign_success_rate"] >= t["adversarial"]["min_benign_success"]
    results.append(("adversarial.benign_success", ok, f"{adv['benign_success_rate']:.0%} ≥ {t['adversarial']['min_benign_success']:.0%}"))

    return results


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


async def run_report(*, gate: bool = True) -> int:
    thresholds = load_thresholds()

    print("Running multi-agent smoke (5 issues)...")
    ma = await run_multi_agent_smoke()

    print("Running scenario smoke (10 scenarios)...")
    sc = await run_scenarios_smoke()

    print("Running adversarial smoke (5+5 tickets)...")
    adv = await run_adversarial_smoke()

    gate_results = check_gate(ma, sc, adv, thresholds)
    md = generate_summary(ma, sc, adv, thresholds, gate_results)

    DOCS_RESULTS.mkdir(parents=True, exist_ok=True)
    out = DOCS_RESULTS / "summary.md"
    out.write_text(md)
    print(md)
    print(f"\nReport written to {out}", file=sys.stderr)

    if gate:
        failures = [r for r in gate_results if not r[1]]
        if failures:
            print(f"\nCI GATE FAILED — {len(failures)} check(s):", file=sys.stderr)
            for name, _, detail in failures:
                print(f"  ✗ {name}: {detail}", file=sys.stderr)
            return 1
        print("\nCI GATE PASSED — all checks OK", file=sys.stderr)
    return 0


def main() -> None:
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-gate", action="store_true", help="Skip CI gate check")
    args = parser.parse_args()
    code = asyncio.run(run_report(gate=not args.no_gate))
    sys.exit(code)


if __name__ == "__main__":
    main()
